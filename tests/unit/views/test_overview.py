def test_the_pages_are_registered_in_a_fixed_order_and_link_each_other(
    view: BuildView,
) -> None:
    pages = render_overview(overview(view()))

    assert sorted(PAGES) == [1, 2, 3, 4, 5]
    assert list(pages) == page_files()
    assert page_files() == [
        "README.md",
        "products.md",
        "repositories.md",
        "risks.md",
        "decisions.md",
    ]
    names = [PAGES[position].name for position in sorted(PAGES)]
    for current, (file, text) in zip(names, pages.items(), strict=True):
        nav = text.splitlines()[4]
        assert f"**{current}**" in nav, file
        for other, target in zip(names, page_files(), strict=True):
            if other != current:
                assert f"[{other}]({target})" in nav, (file, other)


