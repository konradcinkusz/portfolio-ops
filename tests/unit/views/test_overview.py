EVIL = "Evil | <script>x</script> *bold* [link](https://example.invalid) $x$ ~~s~~ &amp;"
HOSTILE = {
    "products.yaml": f"""
        products:
          - id: alpha
            name: '{EVIL}'
            status: active
            next_action: 'Remove ![img](https://example.invalid/i.png) `code` # not a heading'
    """,
    "decisions.md": """
        # Decisions

        ## 2026-09-15 · alpha · focus
        # Not a heading
        - not a list
        1. not ordered
        ---
        <img src=x onerror=alert(1)>
        ```
        not code

        A second paragraph.
    """,
    "findings.yaml": "findings: []\n",
    "risks.yaml": "risks: []\n",
    "kernels.yaml": "kernels: []\n",
}


def unescaped(text: str, raw: str) -> bool:
    """Whether ``raw`` occurs in ``text`` without a backslash right before it."""
    return re.search(rf"(?<!\\){re.escape(raw)}", text) is not None


def test_every_value_from_the_data_is_escaped(view: BuildView) -> None:
    pages = render_overview(overview(view(HOSTILE)))
    text = "\n".join(pages.values())

    assert f"{md(EVIL)} (`alpha`)" in pages["products.md"]
    assert md(EVIL) == (
        "Evil \\| \\<script\\>x\\</script\\> \\*bold\\* \\[link\\](https://example.invalid) "
        "\\$x\\$ \\~\\~s\\~\\~ \\&amp;"
    )
    assert "Remove !\\[img\\](https://example.invalid/i.png) \\`code\\` \\# not a heading" in text
    for raw in ("<script>", "<img", "[link]", "[img]", "*bold*", "$x$", "~~s~~", "&amp;"):
        assert not unescaped(text, raw), raw


