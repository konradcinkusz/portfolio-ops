def test_every_decision_is_on_its_page_newest_first_and_the_latest_on_the_home_page(
    view: BuildView,
) -> None:
    notes = "".join(
        f"## 2026-10-{day:02} · alpha · external\nNote {day}.\n" for day in range(1, 13)
    )
    decisions = (FIXTURES / "valid" / "decisions.md").read_text() + notes
    pages = render_overview(
        overview(view({"decisions.md": decisions}, today=dt.date(2026, 10, 15)))
    )

    assert "All 15 decisions, newest first." in pages["decisions.md"]
    assert re.findall(r"^> Note (\d+)\.$", pages["decisions.md"], re.M) == [
        str(day) for day in range(12, 0, -1)
    ]
    latest = section(pages["README.md"], "Latest decisions")
    assert re.findall(r"^- 2026-10-(\d+) · external", latest, re.M) == [
        "12",
        "11",
        "10",
        "09",
        "08",
    ]
    assert "[Decisions](decisions.md)" in latest
