def overview(view: DashboardInput, **changes: object) -> OverviewInput:
    """The overview's input for the data of a dashboard's."""
    fields = {field.name: getattr(view, field.name) for field in dataclasses.fields(view)}
    return replace(OverviewInput(**fields), **changes)


def pages_match(golden: Golden, scenario: str, pages: dict[str, str]) -> None:
    """Each page equals golden/overview-<scenario>/<page>, where GitHub renders it too."""
    for name, text in pages.items():
        golden(f"overview-{scenario}/{name}", text)


def section(page: str, title: str) -> str:
    """The body of the level-2 section ``title`` of a page."""
    match = re.search(rf"^## {re.escape(title)}\n\n(.*?)(?=^## |\Z)", page, re.M | re.S)
    assert match is not None, title
    return match.group(1)


