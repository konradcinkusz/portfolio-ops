@page(2, "products.md", "Products", "Products")
def products_page(view: OverviewInput) -> list[str]:
    """Every product by status and every kernel; the review dates on a timeline."""
    return [
        *_section("Active", _active(view)),
        *_section("Ideas", _ideas(view)),
        *_section("Paused and dormant", _waiting(view)),
        *_section("Archived", _archived(view)),
        *_section("Kernels", _kernels(view)),
    ]


def _active(view: OverviewInput) -> list[str]:
    portfolio = view.portfolio
    products = _products(portfolio, "active")
    lines = [f"{len(products)} of at most {portfolio.config.thresholds.wip_limit} (wip_limit)."]
    if not products:
        return [*lines, "", "No product is active."]
    if view.clocks is None:
        lines += ["", f"The clocks are not shown: {md(view.no_clocks)}."]
    focus = this_weeks_focus(portfolio, view.today)
    scan = view.account.scan
    rows = []
    for product in products:
        pid = product.id or ""
        name = label(product.name, pid)
        if focus is not None and focus.ids[0] == pid:
            name += ", **focus**"
        row = [
            name,
            md(product.next_action),
            _clock(view, pid),
            _terms(product.capabilities),
            _feeds(view, product),
            _listed(view, product),
        ]
        rows.append(row if scan is None else [*row, _last_push(scan, product)])
    headers = ["Product", "Next action", "Clock", "Capabilities", "Kernels", "Repositories"]
    return [*lines, "", *_table(headers if scan is None else [*headers, "Last push"], rows)]


def _ideas(view: OverviewInput) -> list[str]:
    portfolio = view.portfolio
    products = _products(portfolio, "idea")
    if not products:
        return ["No idea is registered."]
    rows = [
        (
            label(p.name, p.id or ""),
            _terms(p.capabilities),
            _decision_ref(latest_about(portfolio, p.id or "")),
        )
        for p in products
    ]
    return [
        f"{_count(len(products), 'idea')}, not yet through the idea gate.",
        "",
        *_table(("Idea", "Capabilities", "Latest decision"), rows),
    ]


def _waiting(view: OverviewInput) -> list[str]:
    """Products that wait for a review, the soonest first, and their reviews on a timeline."""
    products = sorted(
        _products(view.portfolio, "paused", "dormant"),
        key=lambda p: (p.review_by or dt.date.max, p.id or ""),
    )
    if not products:
        return ["No product is paused or dormant."]
    scan = view.account.scan
    rows = [
        [
            label(p.name, p.id or ""),
            md(p.status),
            md(p.status_reason) or "—",
            _review(p.review_by, view.today),
            md(p.next_action) or "—",
            *([] if scan is None else [_last_push(scan, p)]),
        ]
        for p in products
    ]
    headers = ["Product", "Status", "Reason", "Review by", "Next action"]
    table = _table(headers if scan is None else [*headers, "Last push"], rows)
    return [*table, *_review_chart(view, products)]


def _review(review_by: dt.date | None, today: dt.date) -> str:
    if review_by is None:
        return "—"
    days = (review_by - today).days
    if days < 0:
        return f"{review_by}, **overdue** by {_days(-days)}"
    return f"{review_by}, {'today' if days == 0 else f'in {_days(days)}'}"


def _review_chart(view: OverviewInput, products: Sequence[Product]) -> list[str]:
    """The review dates as Mermaid milestones, with today's: an overdue review is marked
    critical. Today is the page's, not the reader's, so Mermaid's own marker is off."""
    lines = []
    for status in ("paused", "dormant"):
        dated = [p for p in products if p.status == status and p.review_by is not None]
        if dated:
            lines.append(f"    section {status.capitalize()}")
        for product in dated:
            overdue = product.review_by is not None and product.review_by < view.today
            name = chart_label(product.name, product.id or "")
            tags = "crit, milestone" if overdue else "milestone"
            lines.append(f"    Review of {name} : {tags}, {product.review_by}, 0d")
    if not lines:
        return []
    return [
        "",
        "```mermaid",
        "gantt",
        "    title Review dates",
        "    dateFormat YYYY-MM-DD",
        "    axisFormat %Y-%m-%d",
        "    todayMarker off",
        f"    Today : active, milestone, {view.today}, 0d",
        *lines,
        "```",
    ]


