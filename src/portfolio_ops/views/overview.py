"""V3: the overview — the whole portfolio as Markdown pages in the data repository.

GitHub renders Markdown files with tables, links between pages, collapsible sections and
Mermaid charts, and shows them to exactly the people who can read the repository (spec
§7.11, §8.10, ADR 0009). The workflow commits the pages to ``overview/`` of the private
data repository, where they open on the web and in GitHub's mobile app.

A view like the dashboard: it reads the validated portfolio and the values the rules
already derive, and decides nothing. Pages are registered functions in a fixed order, like
the report's sections (P10). Every value from the data is escaped; a Mermaid label keeps
only letters, digits, spaces and a few safe marks; and with ``allow_public`` no private
repository is named. With ``--today`` fixed, the same input renders the same bytes.
"""

