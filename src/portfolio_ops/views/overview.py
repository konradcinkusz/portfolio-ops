def _listing(view: OverviewInput) -> list[str]:
    """Without a scan: the repositories the portfolio lists."""
    owners: tuple[Product | Kernel, ...] = (*view.portfolio.products, *view.portfolio.kernels)
    listed = sorted(
        ((term.value, owner) for owner in owners for term in owner.repos),
        key=lambda pair: pair[0].lower(),
    )
    if not listed:
        return _section("Listed in the portfolio", ["No product or kernel lists a repository."])
    rows = [(_repository(view, name), label(owner.name, owner.id or "")) for name, owner in listed]
    return _section("Listed in the portfolio", _table(("Repository", "Listed by"), rows))


def _ordinal(day: dt.date | None) -> int:
    return day.toordinal() if day is not None else 0


def _named(view: OverviewInput, repository: AccountRepository) -> str:
    flags = [
        kind
        for kind, flag in (
            ("private", repository.private),
            ("fork", repository.fork),
            ("archived", repository.archived),
        )
        if flag
    ]
    return " · ".join([_repository(view, repository.name), *flags])


