@page(4, "risks.md", "Risks and findings", "Risks")
def risks_page(view: OverviewInput) -> list[str]:
    """The risks, those that count as open first; the findings; the copy-paste debt."""
    return [
        *_section("Risks", _risks(view)),
        *_section("Findings", _findings(view)),
        *_section("Copy-paste debt", _debt(view)),
    ]


def _risks(view: OverviewInput) -> list[str]:
    portfolio, today = view.portfolio, view.today
    if not portfolio.risks:
        return ["No risk is registered."]

    def order(risk: Risk) -> tuple[int, int, str]:
        group = 0 if risk.counts_as_open(today) else 1 if risk.state == "accepted" else 2
        return group, -_severity(risk), risk.id or ""

    risks = sorted(portfolio.risks, key=order)
    opened = sum(1 for risk in risks if risk.counts_as_open(today))
    rows = [
        (
            label(risk.title, risk.id or ""),
            _entity(portfolio, risk.scope),
            f"**{risk.severity}**" if risk.severity in SEVERE else md(risk.severity),
            _terms(risk.applies_to),
            _risk_state(risk, today),
        )
        for risk in risks
    ]
    verb = "counts as open and comes" if opened == 1 else "count as open and come"
    return [
        (
            f"{_count(len(risks), 'risk')}; {opened} {verb} first — open, or accepted past "
            "accepted_until."
        ),
        "",
        *_table(("Risk", "Scope", "Severity", "Applies to", "State"), rows),
    ]


def _risk_state(risk: Risk, today: dt.date) -> str:
    if risk.state == "accepted":
        if risk.acceptance_holds(today):
            return f"accepted until {risk.accepted_until}"
        return f"**acceptance ended** {risk.accepted_until}; counts as open"
    return "**open**" if risk.state == "open" else md(risk.state)


def _findings(view: OverviewInput) -> list[str]:
    """What was verified and until when it holds (P2), the soonest to expire first."""
    portfolio, today = view.portfolio, view.today
    config = portfolio.config
    if not portfolio.findings:
        return ["No finding is recorded."]
    dated = sorted(
        ((config.expiry(f), f) for f in portfolio.findings),
        key=lambda pair: (pair[0] or dt.date.max, pair[1].id or ""),
    )
    rows = []
    for until, finding in dated:
        what = label(finding.result, finding.id or "")
        if finding.evidence:
            what += f" — evidence: {md(finding.evidence)}"
        holds = _date(until)
        if until is not None and until < today:
            holds += ", **expired**"
        rows.append(
            (
                what,
                _entity(portfolio, finding.subject),
                md(finding.type),
                _date(finding.checked_on),
                holds,
                _terms(finding.used_in),
            )
        )
    expired = len(_expired(view))
    return [
        (
            f"{_count(len(rows), 'finding')}, the soonest to expire first; {expired} expired — "
            "check an expired one again before it is used."
        ),
        "",
        *_table(("Finding", "Subject", "Type", "Checked on", "Holds until", "Used in"), rows),
    ]


def _debt(view: OverviewInput) -> list[str]:
    portfolio = view.portfolio
    debts = copies(portfolio)
    if not debts:
        return ["No product carries a copy of a kernel."]
    rows = [
        (
            label(product.name, product.id or ""),
            label(kernel.name, kernel.id or ""),
            kernel_state(portfolio, kernel).summary,
        )
        for product, kernel in debts
    ]
    return [
        "Products that carry a copy of a kernel instead of using it as a package:",
        "",
        *_table(("Product", "Kernel", "Kernel state"), rows),
    ]


