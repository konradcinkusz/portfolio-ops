# The first line of every page. It is how ``overview`` tells its own pages from a file it
# must not overwrite, such as the owner's README.
GENERATED = (
    "<!-- Generated by portfolio-ops. The workflow rewrites this page from the data files, "
    "so edit those instead. -->"
)
GENERATED_PREFIX = "<!-- Generated by portfolio-ops"
DEFAULT_SERVER = "https://github.com"
LATEST_DECISIONS = 5  # on the home page; decisions.md has them all
CHART_LABEL_LENGTH = 40
SEVERE = ("high", "critical")


@dataclass(frozen=True)
class OverviewInput:
    portfolio: Portfolio
    today: dt.date
    clocks: Mapping[str, Clock] | None  # N1 for every active product; None without history
    last_data_commit: dt.date | None
    no_clocks: str = ""  # why there is no history to read the clocks from
    account: Account = NOT_SCANNED  # the account scan (§7.12), or why there is none
    server: str = DEFAULT_SERVER  # the GitHub the account's repositories are linked on


PageBody = Callable[[OverviewInput], list[str]]


@dataclass(frozen=True)
class Page:
    file: str
    title: str  # the page's heading
    name: str  # the page in the navigation line
    body: PageBody  # Markdown lines, every value from the data escaped


PAGES: dict[int, Page] = {}


def page(position: int, file: str, title: str, name: str) -> Callable[[PageBody], PageBody]:
    """Register an overview page at its position in the navigation."""

    def register(body: PageBody) -> PageBody:
        if position in PAGES:
            raise ValueError(f"overview position {position} is registered twice")
        PAGES[position] = Page(file, title, name, body)
        return body

    return register


def page_files() -> list[str]:
    """The file name of every page, in the order of the navigation."""
    return [PAGES[position].file for position in sorted(PAGES)]


def render_overview(view: OverviewInput) -> dict[str, str]:
    """Every page by its file name, in the order of the navigation."""
    pages = [PAGES[position] for position in sorted(PAGES)]
    rendered = {}
    for current in pages:
        nav = " · ".join(
            f"**{other.name}**" if other is current else f"[{other.name}]({other.file})"
            for other in pages
        )
        lines = [
            GENERATED,
            "",
            f"# {current.title}",
            "",
            nav,
            "",
            (
                f"Generated by portfolio-ops for {view.today} (UTC). These pages show the state "
                "of the data files and decide nothing: the rules run in validate, the weekly "
                "report and the gates."
            ),
            "",
            *current.body(view),
        ]
        rendered[current.file] = "\n".join(lines).rstrip("\n") + "\n"
    return rendered


# --------------------------------------------------------------------------- Markdown

_MORE = re.compile(r"([~$&])")  # strikethrough, math and character references
_BLOCK = re.compile(r"^(?:([-+=])|(\d{1,9})([.)]))")  # what starts a list or a heading


def md(text: str | None) -> str:
    """A value from the data as inline Markdown on one line: nothing in it formats, links,
    or starts math, strikethrough or an HTML entity."""
    return _MORE.sub(r"\\\1", escape(text or ""))


def chart_label(text: str | None, fallback: str) -> str:
    """Text that Mermaid cannot misread: letters, digits, spaces and ``. - _ /``, on one
    line and at most 40 characters — or the fallback, an id, when nothing is left."""
    kept = "".join(c if c.isalnum() or c in " .-_/" else " " for c in text or "")
    label = " ".join(kept.split())[:CHART_LABEL_LENGTH].strip()
    return label or fallback


def label(name: str | None, ident: str) -> str:
    """``Name (`id`)``, or the id alone when there is no other name."""
    if not name or name == ident:
        return f"`{ident}`"
    return f"{md(name)} (`{ident}`)"


def _entity(portfolio: Portfolio, ident: str | None) -> str:
    """A product, a kernel or a risk by its name, the portfolio, or any other id as it is —
    a risk's scope, a finding's subject, an id in a decision heading."""
    if ident is None or ident == PORTFOLIO:
        return "the portfolio"
    product = portfolio.product(ident)
    if product is not None:
        return label(product.name, ident)
    kernel = portfolio.kernel(ident)
    if kernel is not None:
        return label(kernel.name, ident)
    risk = next((r for r in portfolio.risks if r.id == ident), None)
    return label(risk.title if risk else None, ident)


def _repository(view: OverviewInput, name: str, *, link: bool = True) -> str:
    """A repository as code, linked to it on GitHub."""
    if not is_repository(name):
        return md(name)
    return f"[`{name}`]({view.server.rstrip('/')}/{name})" if link else f"`{name}`"


def _section(title: str, lines: Sequence[str]) -> list[str]:
    return [f"## {title}", "", *lines, ""]


def _table(headers: Sequence[str], rows: Iterable[Sequence[str]]) -> list[str]:
    return [
        f"| {' | '.join(headers)} |",
        f"|{'|'.join('---' for _ in headers)}|",
        *(f"| {' | '.join(row)} |" for row in rows),
    ]


def _quoted(text: str) -> list[str]:
    """A decision's text as a block quote: every line escaped, its line breaks kept."""
    lines = text.split("\n")
    quoted = []
    for index, line in enumerate(lines):
        if not line.strip():
            quoted.append(">")
            continue
        escaped = _BLOCK.sub(
            lambda m: f"\\{m[1]}" if m[1] else f"{m[2]}\\{m[3]}",
            md(line),
        )
        follows = index + 1 < len(lines) and lines[index + 1].strip()
        quoted.append(f"> {escaped}\\" if follows else f"> {escaped}")
    return quoted


def _terms(terms: Iterable[Term] | None) -> str:
    values = [md(term.value) for term in terms or ()]
    return ", ".join(values) if values else "—"


def _joined(items: Sequence[str], empty: str = "—") -> str:
    return "; ".join(items) if items else empty


def _paragraphs(texts: Sequence[str]) -> list[str]:
    """Texts as paragraphs, a blank line between each two."""
    lines: list[str] = []
    for text in texts:
        lines += [text, ""]
    return lines[:-1]


def _days(count: int) -> str:
    return "1 day" if count == 1 else f"{count} days"


def _count(number: int, noun: str) -> str:
    plural = f"{noun[:-1]}ies" if noun.endswith("y") else f"{noun}s"
    return f"{number} {noun}" if number == 1 else f"{number} {plural}"


def _date(value: dt.date | None) -> str:
    return "—" if value is None else str(value)


# --------------------------------------------------------------------------- the portfolio


def _products(portfolio: Portfolio, *statuses: str) -> list[Product]:
    return [p for p in portfolio.products if p.status in statuses and p.id is not None]


def _stale(view: OverviewInput) -> list[tuple[Product, Clock]]:
    """The active products whose clock is past stale_days (N2), the oldest first."""
    if view.clocks is None:
        return []
    limit = view.portfolio.config.thresholds.stale_days
    found = []
    for product_id, clock in view.clocks.items():
        product = view.portfolio.product(product_id)
        if product is not None and clock.days > limit:
            found.append((product, clock))
    return sorted(found, key=lambda pair: (-pair[1].days, pair[0].id or ""))


def _overdue(view: OverviewInput) -> list[Product]:
    """Paused and dormant products whose review is overdue (N4), the longest overdue first."""
    return sorted(
        (
            p
            for p in _products(view.portfolio, "paused", "dormant")
            if p.review_by is not None and p.review_by < view.today
        ),
        key=lambda p: (p.review_by, p.id or ""),
    )


def _ended(view: OverviewInput) -> list[Risk]:
    """Accepted risks whose acceptance has ended: they count as open again (B3)."""
    return [
        risk
        for risk in view.portfolio.risks
        if risk.state == "accepted" and not risk.acceptance_holds(view.today)
    ]


def _severity(risk: Risk) -> int:
    return SEVERITIES.index(risk.severity) if risk.severity in SEVERITIES else 0


def _expired(view: OverviewInput) -> list[tuple[dt.date, Finding]]:
    """Findings past their expiry (P2), the longest expired first."""
    config = view.portfolio.config
    found = [
        (until, finding)
        for finding in view.portfolio.findings
        if (until := config.expiry(finding)) is not None and until < view.today
    ]
    return sorted(found, key=lambda pair: (pair[0], pair[1].id or ""))


def _clock(view: OverviewInput, product_id: str) -> str:
    clock = view.clocks.get(product_id) if view.clocks is not None else None
    if clock is None:
        return "—"
    text = f"{_days(clock.days)} since {clock.since}"
    stale = clock.days > view.portfolio.config.thresholds.stale_days
    return f"{text}, **stale**" if stale else text


def _feeds(view: OverviewInput, product: Product) -> str:
    items = []
    for feed in product.feeds_from:
        kernel = view.portfolio.kernel(feed.kernel or "")
        mode = f"**{feed.mode}**" if feed.mode == "copy" else md(feed.mode)
        items.append(f"{label(kernel.name if kernel else None, feed.kernel or '')}, {mode}")
    return _joined(items)


def _listed(view: OverviewInput, owner: Product | Kernel) -> str:
    return ", ".join(_repository(view, term.value) for term in owner.repos) or "—"


def _decision_ref(decision: Decision | None) -> str:
    return "—" if decision is None else f"{decision.date} · {md(decision.type)}"


def _last_push(scan: AccountScan, owner: Product | Kernel) -> str:
    """The latest push to the repositories a product or a kernel lists."""
    by_name = {r.name.lower(): r for r in scan.repositories}
    pushes = [
        repository.pushed_on
        for term in owner.repos
        if (repository := by_name.get(term.value.lower())) is not None
        and repository.pushed_on is not None
    ]
    return _date(max(pushes)) if pushes else "—"


