@page(1, "README.md", "Portfolio overview", "Overview")
def home(view: OverviewInput) -> list[str]:
    """The numbers at a glance, what needs attention, this week, where the week's work went
    and the latest decisions."""
    return [
        *_section("At a glance", _glance(view)),
        *_section("Needs attention", _attention(view)),
        *_section("This week", _this_week(view)),
        *_section("Where the work went", _work(view)),
        *_section("Latest decisions", _latest(view)),
    ]


def _glance(view: OverviewInput) -> list[str]:
    portfolio, today = view.portfolio, view.today
    thresholds = portfolio.config.thresholds
    focus = this_weeks_focus(portfolio, today)
    if focus is None:
        focused = "**none recorded**"
    else:
        focused = f"{_entity(portfolio, focus.ids[0])}, recorded {focus.date}"
    if view.clocks is None:
        stale = "— (no clocks without the git history)"
    else:
        stale = f"{len(_stale(view))} (stale_days: {thresholds.stale_days})"
    waiting = len(_products(portfolio, "paused", "dormant"))
    overdue = len(_overdue(view))
    open_risks = [risk for risk in portfolio.risks if risk.counts_as_open(today)]
    severe = sum(1 for risk in open_risks if risk.severity in SEVERE)
    states = [kernel_state(portfolio, kernel).state for kernel in portfolio.kernels]
    kernels = ", ".join(f"{states.count(s)} {s}" for s in ("done", "extracted", "planned"))
    rows = [
        (
            "[Active products](products.md#active)",
            f"{len(_products(portfolio, 'active'))} of {thresholds.wip_limit} (wip_limit)",
        ),
        ("Focus this week", focused),
        ("Stale products", stale),
        ("[Ideas](products.md#ideas)", str(len(_products(portfolio, "idea")))),
        (
            "[Paused or dormant](products.md#paused-and-dormant)",
            f"{waiting}, {_count(overdue, 'review')} overdue" if overdue else str(waiting),
        ),
        ("[Archived](products.md#archived)", str(len(_products(portfolio, "archived")))),
        ("[Kernels](products.md#kernels)", f"{len(states)}: {kernels}" if states else "0"),
        ("[Open risks](risks.md#risks)", f"{len(open_risks)}, {severe} high or critical"),
        (
            "[Findings](risks.md#findings)",
            f"{len(portfolio.findings)}, {len(_expired(view))} expired",
        ),
        ("[Copy-paste debt](risks.md#copy-paste-debt)", str(len(copies(portfolio)))),
        ("[Repositories worked on](repositories.md)", _worked_summary(view)),
        ("Data last committed", _date(view.last_data_commit)),
    ]
    return _table(("Measure", "Now"), rows)


def _worked_summary(view: OverviewInput) -> str:
    account, scan = view.account, view.account.scan
    if scan is None:
        return "**the scan failed**" if account.failed else "— (the account is not scanned)"
    worked = sum(1 for r in shown(scan) if worked_on(r, scan) is not None)
    outside = len(outside_portfolio(view.portfolio, scan))
    only = ", **public repositories only**" if not scan.sees_private else ""
    return f"{worked} since {scan.since}, {outside} outside the portfolio{only}"


def _attention(view: OverviewInput) -> list[str]:
    """What the weekly report and the dashboard make stand out, each with where to look."""
    portfolio, today = view.portfolio, view.today
    items = []
    stale = _stale(view)
    if stale:
        limit = portfolio.config.thresholds.stale_days
        names = [f"{label(p.name, p.id or '')}, {_days(c.days)}" for p, c in stale]
        items.append(
            f"**Stale:** {_joined(names)} — the clock is past stale_days ({limit}). See "
            "[the active products](products.md#active)."
        )
    overdue = _overdue(view)
    if overdue:
        names = [f"{label(p.name, p.id or '')}, due {p.review_by}" for p in overdue]
        items.append(
            f"**Reviews overdue:** {_joined(names)}. See "
            "[paused and dormant](products.md#paused-and-dormant)."
        )
    ended = _ended(view)
    if ended:
        names = [f"{label(r.title, r.id or '')}, accepted until {r.accepted_until}" for r in ended]
        items.append(
            f"**Acceptances ended:** {_joined(names)} — they count as open again. See "
            "[the risks](risks.md#risks)."
        )
    severe = sorted(
        (r for r in portfolio.risks if r.state == "open" and r.severity in SEVERE),
        key=lambda r: (-_severity(r), r.id or ""),
    )
    if severe:
        names = [f"{label(r.title, r.id or '')}, {r.severity}" for r in severe]
        items.append(
            f"**Open high or critical risks:** {_joined(names)}. See [the risks](risks.md#risks)."
        )
    expired = _expired(view)
    if expired:
        names = [f"{label(f.result, f.id or '')}, held until {until}" for until, f in expired]
        items.append(
            f"**Expired findings:** {_joined(names)} — check each again before it is used. "
            "See [the findings](risks.md#findings)."
        )
    debt = copies(portfolio)
    if debt:
        names = [
            f"{label(p.name, p.id or '')} carries a copy of {label(k.name, k.id or '')}"
            for p, k in debt
        ]
        items.append(
            f"**Copy-paste debt:** {_joined(names)}. See "
            "[the copy-paste debt](risks.md#copy-paste-debt)."
        )
    items += _account_attention(view)
    if this_weeks_focus(portfolio, today) is None:
        items.append(
            f"**No focus recorded this week.** Record one in {DECISIONS_FILE} as "
            f"`## {today} · <product> · focus`."
        )
    if not items:
        return ["Nothing needs attention."]
    return [f"- {item}" for item in items]


def _account_attention(view: OverviewInput) -> list[str]:
    account, portfolio = view.account, view.portfolio
    scan = account.scan
    if scan is None:
        if account.failed:
            return [f"**The account was not scanned.** {md(account.problem)}."]
        return []
    items = []
    blind = blind_spot(scan)
    if blind:
        items.append(f"**The token sees only public repositories:** {md(blind)}.")
    outside = outside_portfolio(portfolio, scan)
    if outside:
        items.append(
            f"**Work outside the portfolio:** {_count(len(outside), 'repository')} you worked "
            f"on since {scan.since} {'belongs' if len(outside) == 1 else 'belong'} to no "
            "product or kernel. See [the week's repositories](repositories.md#worked-on-this-week)."
        )
    inactive = inactive_work(portfolio, scan)
    if inactive:
        names = [
            f"{label(w.product.name, w.product.id or '')}, {w.product.status}, in "
            f"{_repository(view, w.repository.name)}"
            for w in inactive
        ]
        items.append(f"**Products that are not active, worked on:** {_joined(names)}.")
    unknown = unknown_repositories(portfolio, scan)
    if unknown:
        names = [
            f"{_repository(view, u.term.value, link=False)}, listed by "
            f"{label(u.owner.name, u.owner.id or '')}"
            for u in unknown
        ]
        items.append(
            f"**Listed repositories the account does not have:** {_joined(names)}. See "
            "[the repositories](repositories.md#listed-but-not-found)."
        )
    return items


def _this_week(view: OverviewInput) -> list[str]:
    portfolio = view.portfolio
    focus = this_weeks_focus(portfolio, view.today)
    if focus is None:
        lines = ["**No focus recorded this week.**"]
    else:
        lines = [f"Focus: {_entity(portfolio, focus.ids[0])}, recorded {focus.date}."]
    active = _products(portfolio, "active")
    if not active:
        return [*lines, "", "No product is active."]
    if view.clocks is None:
        lines += ["", f"The clocks are not shown: {md(view.no_clocks)}."]
    scan = view.account.scan
    headers = ["Product", "Next action", "Clock"]
    rows = []
    for product in active:
        row = [
            label(product.name, product.id or ""),
            md(product.next_action),
            _clock(view, product.id or ""),
        ]
        rows.append(row if scan is None else [*row, _last_push(scan, product)])
    return [*lines, "", *_table(headers if scan is None else [*headers, "Last push"], rows)]


def _work(view: OverviewInput) -> list[str]:
    """The repositories with the owner's activity in the window, by the product or kernel
    that lists them, as a Mermaid pie."""
    account = view.account
    scan = account.scan
    if scan is None:
        return [f"The account was not scanned: {md(account.problem)}."]
    visible = shown(scan)
    worked = [r for r in visible if worked_on(r, scan) is not None]
    if not worked:
        return [
            (
                f"No activity of yours since {scan.since} in the "
                f"{_count(len(visible), 'repository')} scanned."
            )
        ]
    lines = [
        (
            f"Your activity since {scan.since} is in {len(worked)} of the "
            f"{_count(len(visible), 'repository')} scanned. The chart groups them by the "
            "product or kernel that lists them, and "
            "[the repositories page](repositories.md#worked-on-this-week) names them."
        ),
        "",
        "```mermaid",
        "pie showData",
        f"    title Repositories with your activity since {scan.since}",
        *(f'    "{name}" : {count}' for name, count in _slices(view, worked)),
        "```",
    ]
    if not scan.sees_private:
        lines += [
            "",
            "The token sees only public repositories, so work in private ones is missing.",
        ]
    return lines


def _slices(view: OverviewInput, worked: Sequence[AccountRepository]) -> list[tuple[str, int]]:
    """The pie's slices, the largest first: one for each product or kernel, one for the
    ignored repositories and one for those outside the portfolio."""
    listed = listing(view.portfolio)
    counts: dict[str, int] = {}
    names: dict[str, tuple[str, str]] = {}  # a slice's key: its label, and its id
    for repository in worked:
        owner = listed.get(repository.name.lower())
        if isinstance(owner, Product):
            key = f"product {owner.id}"
            status = "" if owner.status == "active" else f" ({owner.status})"
            names[key] = (chart_label(owner.name, owner.id or "") + status, owner.id or "")
        elif owner is not None:
            key = f"kernel {owner.id}"
            names[key] = (chart_label(owner.name, owner.id or "") + " (kernel)", owner.id or "")
        elif ignored(view.portfolio, repository.name):
            key, names[key] = "ignored", ("Ignored", "")
        else:
            key, names[key] = "outside", ("Outside the portfolio", "")
        counts[key] = counts.get(key, 0) + 1
    # Mermaid joins slices that share a label, so a label used twice takes its id along.
    taken = [names[key][0] for key in counts]
    slices = []
    for key, count in counts.items():
        name, ident = names[key]
        slices.append((name if taken.count(name) == 1 else f"{name} {ident}", count))
    return sorted(slices, key=lambda pair: (-pair[1], pair[0]))


def _latest(view: OverviewInput) -> list[str]:
    portfolio = view.portfolio
    every = newest_first(portfolio)
    if not every:
        return ["No decision is recorded yet."]
    lines = [
        f"- {d.date} · {md(d.type)} · {', '.join(_entity(portfolio, i) for i in d.ids)}"
        for d in every[:LATEST_DECISIONS]
    ]
    return [*lines, "", "Every decision, with its text: [Decisions](decisions.md)."]


